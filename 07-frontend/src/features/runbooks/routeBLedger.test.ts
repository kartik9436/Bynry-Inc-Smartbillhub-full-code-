/**
 * The Runbooks feature root is on the Route B ledger, and stays there.
 *
 * WHY A TEST AND NOT A COMMENT
 * ----------------------------
 * `CR-075`'s trap 1, and it is the one that ships an INVISIBLE product. A
 * Tailwind utility is emitted only for a file the ledger covers. Write one in a
 * file the ledger does not cover and the class is declared by no stylesheet and
 * generated by no compiler: **the screen renders as nothing at all**, while
 * `tsc`, eslint and every `toContain("flex")` assertion PASS, because the class
 * IS in the DOM. Two lanes paid for exactly this in one week — `DEF-974` and
 * `DEF-901` — and both were fixing OTHER UI defects at the time, so both fixes
 * would have re-broken the screen they had just repaired.
 *
 * The ledger line is therefore written in wave A, before any component exists,
 * and this file is what makes the line load-bearing rather than decorative:
 * delete `features/runbooks/` from the ledger and this goes RED by name. A
 * comment claiming the entry is there is not the entry (hard-won law 1).
 *
 * WHY A DIRECTORY ENTRY AND NOT A LIST OF FILES
 * ---------------------------------------------
 * A trailing `/` names a directory and both readers expand it — G31's
 * `route_b_migrated()` and `src/styles/routeBUtilities.test.ts`. The per-file
 * ledger sets the trap it was written to close: wave D adds
 * `features/runbooks/RunResultPage.tsx`, forgets the ledger, and its utilities
 * render as nothing. `portal/` took this shape on 2026-09-03 (`CR-068` wave A)
 * for the same reason and it is the shape that closes `DEF-974` rather than
 * re-arming it once per file.
 *
 * WHAT WOULD MAKE THIS TEST PASS WRONGLY
 * --------------------------------------
 * A ledger line without the trailing slash — `features/runbooks` — reads to
 * both expanders as a FILE that does not exist, so it covers nothing while
 * looking present in a grep. The first assertion below therefore matches the
 * slash exactly rather than by `includes`. A commented-out line is likewise not
 * an entry: comment lines are stripped before the comparison, exactly as both
 * readers strip them.
 *
 * ⚠ WAVE A WRITES NO COMPONENT, so the directory holds only this file today.
 * That is deliberate and the execution plan says so — wave A is the one wave in
 * `CR-075` with no screen a clerk can open. `routeBUtilities.test.ts` excludes
 * `.test.` files from its expansion, so this file is not itself checked for
 * class tokens and adds nothing to that check's corpus.
 */

import { describe, expect, it } from "vitest";

// ⚠ NODE'S OWN MODULES, REACHED THE WAY `styles/routeBUtilities.test.ts` AND
// `tailwindTheme.test.ts` NEXT DOOR DO, AND THE FIRST DRAFT OF THIS FILE DID IT
// THE OBVIOUS WAY AND WAS WRONG. `import fs from "node:fs"` type-checks against
// `@types/node`, which this app's `tsconfig.json` does not include — its `lib`
// is `ES2022 · DOM · DOM.Iterable` and nothing else — so `tsc --noEmit` answers
// `TS2307: Cannot find module 'node:fs'` and `TS2304: Cannot find name
// '__dirname'`. **Vitest was green over it anyway**, because it transpiles
// without type-checking, which is the whole reason the type check is a separate
// command and has to be run.
//
// The string-split form keeps Vite from pre-bundling the import, and the cast
// declares exactly the surface used here — so the file is typed by what it
// asks for rather than by a dependency this app does not carry.
const nodeFs = (await import(/* @vite-ignore */ ["node", "fs"].join(":"))) as {
  readFileSync(p: string, enc: string): string;
  existsSync(p: string): boolean;
};
const nodePath = (await import(/* @vite-ignore */ ["node", "path"].join(":"))) as {
  join(...p: string[]): string;
  dirname(p: string): string;
  resolve(...p: string[]): string;
};
const nodeUrl = (await import(/* @vite-ignore */ ["node", "url"].join(":"))) as {
  fileURLToPath(url: URL | string): string;
};

// `__dirname` does not exist in an ES module and is not declared by this app's
// `lib`; `import.meta.url` is the form that is both correct at runtime and
// typed without `@types/node`.
const HERE = nodePath.dirname(nodeUrl.fileURLToPath(import.meta.url));
const SRC = nodePath.resolve(HERE, "..", "..");
const LEDGER = nodePath.join(SRC, "styles", "route-b-migrated.txt");
const ENTRY = "features/runbooks/";

/** The ledger as both readers read it: trimmed, blank and comment lines gone. */
function ledgerEntries(): string[] {
  return nodeFs
    .readFileSync(LEDGER, "utf8")
    .split("\n")
    .map((line: string) => line.trim())
    .filter((line: string) => line !== "" && !line.startsWith("#"));
}

describe("CR-075 wave A · the Runbooks feature root is Tailwind-owned from its first commit", () => {
  it("route-b-migrated.txt carries the `features/runbooks/` DIRECTORY entry", () => {
    const entries = ledgerEntries();
    expect(
      entries,
      "B14 rule 21's migration clause is PER FILE. Without this entry every Tailwind " +
        "utility waves C-E write under features/runbooks/ is a class no stylesheet " +
        "declares and no compiler generates: the screen renders as NOTHING while tsc, " +
        "eslint and every toContain() assertion pass (DEF-974, DEF-901).",
    ).toContain(ENTRY);
  });

  it("the entry ends in a slash, so it covers files that do not exist yet", () => {
    const entries = ledgerEntries();
    const near = entries.filter((line) => line.replace(/\/$/, "") === "features/runbooks");
    expect(
      near,
      "A ledger line without its trailing slash reads to BOTH expanders as a file " +
        "that does not exist. It covers nothing and still answers a grep.",
    ).toEqual([ENTRY]);
  });

  it("the directory the entry names exists, so the expansion is live rather than skipped", () => {
    // `routeBUtilities.test.ts` falls back to treating a missing folder as a
    // literal path (`if (!existsSync(folder)) return [entry]`), which would make
    // this ledger line a silent no-op. The folder holding this very file is the
    // proof it does not.
    expect(nodeFs.existsSync(nodePath.join(SRC, ENTRY))).toBe(true);
  });
});

