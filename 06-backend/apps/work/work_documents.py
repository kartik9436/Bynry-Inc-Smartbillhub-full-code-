#: The band the phone aims for (PO 2026-10-04: "compress images to 70 to 100
#: Kb before you upload"). The server's shrink lands in it too.
TARGET_MIN_BYTES = 70 * 1024


class NotAnImage(ValueError):
    """The bytes are not a picture Pillow can read — not a photograph."""


def shrink_photo(data: bytes) -> tuple[bytes, str]:
    """`(bytes, content_type)` — the photograph at or under `MAX_PHOTO_BYTES`.

    Under the ceiling already: returned UNTOUCHED (a phone that compressed
    correctly is never re-compressed). Over it: the long edge is brought to
    `PHOTO_LONG_EDGE_PX` and JPEG quality is stepped down from 85 until the
    bytes fit; if quality 30 still does not fit, the picture is scaled down a
    further 20% at a time. It always ends under the ceiling — a 1 px image is
    — so nothing here can refuse a real photograph.
    """
    if not data:
        raise NotAnImage("zero bytes is not a photograph")
    from PIL import Image, UnidentifiedImageError

    try:
        probe = Image.open(io.BytesIO(data))
        probe.verify()
        image = Image.open(io.BytesIO(data))
        image.load()
    except (UnidentifiedImageError, OSError, SyntaxError, ValueError) as exc:
        raise NotAnImage(str(exc)) from exc
    if len(data) <= MAX_PHOTO_BYTES:
        fmt = (image.format or "JPEG").lower()
        return data, f"image/{'jpeg' if fmt == 'jpg' else fmt}"
    image = image.convert("RGB")
    scale = 1.0
    longest = max(image.size)
    if longest > PHOTO_LONG_EDGE_PX:
        scale = PHOTO_LONG_EDGE_PX / longest
    while True:
        size = (max(1, int(image.size[0] * scale)), max(1, int(image.size[1] * scale)))
        frame = image.resize(size) if scale != 1.0 else image
        for quality in range(85, 25, -5):
            out = io.BytesIO()
            frame.save(out, format="JPEG", quality=quality, optimize=True)
            if out.tell() <= MAX_PHOTO_BYTES:
                return out.getvalue(), "image/jpeg"
        scale *= 0.8
