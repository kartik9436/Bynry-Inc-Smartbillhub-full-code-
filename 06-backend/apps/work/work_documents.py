#: **100 KB, and it is the PO's number rather than an engineering guess.**
#: 100 * 1024 and not 100_000: the phone's compressor works in binary
#: kilobytes, and a decimal ceiling would refuse a file the handset had
#: correctly compressed to "100 KB" — a refusal nobody could act on, on the
#: last photograph of a nine-photograph day.
MAX_PHOTO_BYTES = 100 * 1024

#: What the handset aims for on the long side to REACH that ceiling. ⚠ **THIS
#: IS THE MECHANISM AND NOT THE TARGET, AND IT USED TO BE THE TARGET.**
#: `BR-WRK-047` said *"resizes to 1,600 px"* until 2026-09-05, when the PO's
#: ruling made the BYTES the rule. A 1,600 px photograph of a dark meter
#: cupboard can still exceed 100 KB — dark, noisy images compress badly — so
#: the client resizes to this and then steps quality down until the bytes fit.
#: A client that resizes and stops has not complied.
PHOTO_LONG_EDGE_PX = 1600

#: Twelve months. See the module docstring for the ruling this came from.
RETENTION_MONTHS = 12


class ExportPathMissing(RuntimeError):
    """Raised by `prune_due()`. Nothing may be deleted before the export exists."""


@dataclass(frozen=True)
class RetentionPolicy:
    """The ruled regime, as data rather than as prose in six documents.

    Frozen because it is a RULING and not a setting: a tenant does not get to
    shorten it and a lane does not get to widen it. Changing any field here is
    a new PO ruling, and `BR-WRK-048` is where that conversation starts.
    """

    months: int
    export_before_delete: bool
    held_while_matter_open: bool
    export_path_built: bool

    @property
    def may_prune(self) -> bool:
        """Whether anything may lawfully be deleted today. It may not.

        Two conditions, and the second is the one that is false: the regime
        must require an export (it does), and that export must EXIST (it does
        not). Written as a property rather than a constant so the day somebody
        builds the download path, this answer changes by itself.
        """
        return (not self.export_before_delete) or self.export_path_built


def retention_policy() -> RetentionPolicy:
    """How long a job's photographs, signatures and reports are kept.

    ⚠ **THIS DOES NOT RAISE, AND IT USED TO BE SPECIFIED AS A STUB THAT DID.**
    `OQ-WRK-1496` closed on 2026-09-04 — twelve months, then an export before
    deletion. See the module docstring for the PO's words and the arithmetic.

    `export_path_built=False` is a statement of fact about this repo, not a
    setting: no download path exists for a job's evidence, and until one does
    `prune_due()` refuses. It is a literal rather than a feature flag because a
    flag invites somebody to flip it, and the thing that makes it true is a
    story nobody has written yet.
    """
    return RetentionPolicy(
        months=RETENTION_MONTHS,
        export_before_delete=True,
        held_while_matter_open=True,
        export_path_built=False,
    )


def prune_due(*, now=None):  # noqa: ANN001, ANN201 — never returns; see below
    """What is past its twelve months and may be deleted. Nothing, today.

    ⚠ **THIS RAISES, AND THE REASON IS THE RULING RATHER THAN A GAP IN IT.**
    The PO ruled twelve months AND an export first: *"allow them to take a
    backup by downloading it on local drive - we will delete it from our
    stoagre"*. The download path does not exist, so deleting on the twelve-month
    boundary would take a utility's evidence with no backup ever offered —
    honouring half a ruling, which is worse here than honouring none of it.

    The pruning job for Work kinds is **not scheduled**, and this function is
    called by nothing in production. It exists so that the refusal is written
    down in the one place a lane looking for the pruning job will land, instead
    of that lane concluding from an absence that nobody had got to it yet.
    """
    policy = retention_policy()
    if not policy.may_prune:
        raise ExportPathMissing(
            "refusing to select work-order evidence for deletion: the Product Owner "
            f"ruled {policy.months} months AND an export before deletion (2026-09-04, "
            "OQ-WRK-1496 — 'allow them to take a backup by downloading it on local "
            "drive - we will delete it from our stoagre'), and no download path exists "
            "yet. An export that does not exist is not a retention policy. Build the "
            "export, tell the utility, then schedule the prune — in that order. "
            "A photograph attached to an open dispute or an unresolved service request "
            "is held past the window even once this is unblocked."
        )
    raise AssertionError(  # pragma: no cover — unreachable while may_prune is False
        "retention_policy().may_prune became True without a pruning implementation. "
        "Whoever built the export path must write the selection here, honouring the "
        "open-matter hold."
    )


def check_photo_bytes(byte_length: int) -> None:
    """Refuse a file the handset should have compressed. Names both numbers.

    See the module docstring: the PO's ruling binds the app, and this is where
    it stops being a hope. The message is written for whoever reads it in a log
    at 17:40 after an offline day, so it says what arrived, what the ceiling is,
    and what the phone was supposed to have done.
    """
    if byte_length <= 0:
        raise ValueError(
            "refusing a zero-byte photograph. Zero bytes is the shape a failed capture "
            "takes, and storing one would make 'the meter was photographed' true about "
            "an empty file."
        )
    if byte_length > MAX_PHOTO_BYTES:
        raise ValueError(
            f"photograph is {byte_length:,} bytes; the ceiling is {MAX_PHOTO_BYTES:,} "
            f"(100 KB, PO ruling 2026-09-04 on OQ-WRK-1496). The handset compresses at "
            f"capture — resize the long edge to {PHOTO_LONG_EDGE_PX} px and step quality "
            "down until the bytes fit; the pixel size alone is not enough, because a "
            "dark meter cupboard compresses badly. The raw original is never uploaded."
        )


