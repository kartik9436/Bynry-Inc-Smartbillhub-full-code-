        # ── CR-150-BRC09 · THE SAME SEVEN KEYS A BUILD ROW CARRIES ─────────
        # ⚠ **PRESENT AND NULL, NEVER OMITTED** — this function's own opening
        # rule: *"Every key a build row carries is carried here, with a NAMED
