def _search(qs: Any, q: str | None) -> Any:
    """B18 §5.4.2's placeholder, verbatim: *"Connection #, premise, address,
    applicant, or request #…"* — five things, so five columns.

    `applicant` and `request #` live on `customers.ServiceRequest` and are
    reached through `Connection.service_request`, the cross-module FK B18 §5.4.6
    draws and `connections.py` declares. This is a READ across a declared FK
    (B2 §2's reviewed interface set), not a cross-module write.
    """
    if not q:
        return qs
    return qs.filter(
        Q(connection_no__icontains=q)
        | Q(premises__premise_no__icontains=q)
        | Q(premises__name__icontains=q)
        | Q(premises__address_line__icontains=q)
        | Q(service_request__request_no__icontains=q)
        | Q(service_request__applicant_name__icontains=q)
    )


def _page_number(raw: Any, last: int) -> int:
    """BR-SHL-011 *"never error"*: garbage or out-of-range clamps into
    `[1, last]`. `StandardPagination.get_page_number`'s rule, applied here
    because this selector — not the paginator — does the slicing (§4)."""
    try:
        number = int(str(raw))
    except (TypeError, ValueError):
        number = 1
    return min(max(number, 1), max(last, 1))


def _unit_counts(tenant_id: UUID, connection_ids: list[Any]) -> dict[Any, int]:
    """`NCT-01`'s `UNITS` column — how many units this build touches.

    A build's units are the ones its SERVICES name, not every unit standing on
    the premise: a later connection on an existing block would otherwise report
    the whole block. A per-premise service (`unit_id` NULL — the main tap, the
    building's trash) belongs to the build and to no unit, so it is excluded
    rather than counted as a unit.

    One grouped query for the whole page, not one per row: this is a COUNT and
    not a derivation, so there is no rule to route through `connections.py`.
    """
    if not connection_ids:
        return {}
    rows = (
        work_tables.ConnectionService.objects.filter(
            tenant_id=tenant_id, connection_id__in=connection_ids, unit__isnull=False
        )
        .values("connection_id")
        .annotate(units=Count("unit_id", distinct=True))
    )
    return {row["connection_id"]: row["units"] for row in rows}


