def list_connections(
    *,
    segment: str = SEGMENT_ALL,
    q: str | None = None,
    page: Any = 1,
    per: Any = DEFAULT_PAGE_SIZE,
    filters: dict[str, Any] | None = None,
    sort: str | None = None,
    dir: str = DEFAULT_DIR,
) -> dict[str, Any]:
    """`NCT-01` — the worklist page and its KPI strip.

    Returns `{"rows", "kpis", "page", "per", "total"}`. `page`/`per` come back
    as the values that were USED after clamping, so a caller that asked for
    `page=99&per=75` is told it got page 3 of 50-row pages rather than having to
    work it out (BR-SHL-011: fall back or clamp, never error).

    ⛔ **`segment` accepts `all` and nothing else** — see §3. Every other value
    raises `NotImplementedError("OQ-371")`, including the four `NCT-01` draws,
    because which exclusive tab holds a build that is `partly_activated` AND
    waiting is a question only the PO can answer and a wrong answer hides a
    build rather than failing.

    ⚠ **IT OPENS ON THE CREATION ORDER SINCE 2026-09-12 (`BR-CUS-1046`,
    `DEF-CUS-5060`).** This paragraph used to read *"Sorted by target date,
    soonest first"*, quoting B18 §5.4.2's footnote and the sentence the tab
    printed under its pager. The PO ruled (2026-09-10, extended 2026-09-12):
    *"The new newly created entries should always show on the top … (c) All
    eight open newest-first and the six gain a sort control."*

    ⚠ **B18 §5.4.2's ORDERING IS NOT LOST — IT IS `sort="target"`**, a clickable
    column whose choice survives a refresh, and the nulls-last rule it carried
    is intact in both directions: a build with NO target sorts LAST rather than
    first, because a missing date is not the most urgent thing on the list. `id`
    breaks ties on every sort so the order is stable across pages (IS-2).
    """
    if segment != SEGMENT_ALL:
        raise NotImplementedError("OQ-371")

    tenant_id = _tenant_id()
    qs = _search(
        _connections(tenant_id).select_related("premises", "service_request"),
        (q or "").strip() or None,
    )
    # ── `f.state`, applied in SQL — CR-045 wave D task D.11, WIDENED to the
    #    blueprint's chips (`DEF-CUS-5431`) ─────────────────────────────────
    #
    # ⚠ **THE COMMENT THAT STOOD HERE DESCRIBED A WINDOW THAT DOES NOT EXIST,
    # AND IT COST A LIVE FILTER.** It read *"this list is the OPEN worklist, so
    # `activated` and `cancelled` are already outside it (see `_connections`'
    # window)"* and concluded that offering either *"would be a control that
    # always answers none"*. **`_connections` has no window** — it is
    # `Connection.objects.filter(tenant_id=tenant_id)` and nothing else, three
    # functions above — so an activated build IS in this list, the blueprint
    # draws one (`CX-26-0004 · Activated`), and `f.state=activated` narrowed it
    # to ZERO rows while those rows sat in the unfiltered page. A filter that
    # empties a list on a value the drawing offers is worse than an absent one.
    # Hard-won law 1: a comment claiming a guarantee is not the guarantee.
    #
    # Three legs, and all three are `WHERE` clauses — nothing is pulled and
    # narrowed in Python, because a T5 utility is 40,000 accounts (`NFR-3`):
    #   · `open`  → the KPI tile's own set, `state IN (…)`
    #   · a state → `state = …`
