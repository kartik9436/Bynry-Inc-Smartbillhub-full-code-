def parks_queryset(*, q: str | None = None, filters: dict[str, Any] | None = None):
    """The new connects a clerk started and put down - `wizard_parks`.

    ⚠ **THE WINDOW, NOT A COLUMN.** PO 2026-09-20, verbatim: *"remove it - it is
    anyway in the list so we dont need it sepretely - if it is not in list add
    it"*. Until that day a parked new connect was drawn on a pinned PANEL above
    this table (`CR-035` amendment 1) and this list could not see it at all.
    `move_reads.move_out_parks_queryset` is the shape being copied, written one
    day earlier for the Move-outs tab, rather than a second answer designed.

    ⚠ **READ THROUGH METERING'S OWN SEAM, NEVER THE TABLE** (B1 / BR-TEN-013;
    G6 rule 4). `seams.wizard_park_queryset` forwards to the owning module's own
    queryset, which carries the tenant filter under RLS `FORCE` - hard rule 1
    applied where the queryset is BUILT.

    ⚠ **`f.state` IS EXCLUSIVE BETWEEN THE TWO SOURCES**, which is what lets one
    filter work over two tables: the build arm answers `work_tables.CONNECTION_STATES`
    plus `open`, this one answers the two draft codes, and each returns NONE
    rather than EVERYTHING for a value it does not own (BR-SHL-011).
    """
    rows = seams.wizard_park_queryset(flow="new_connect")

    state = (filters or {}).get("state")
    if state and str(state) not in (
        NEW_CONNECT_STATE_IN_PROGRESS_DRAFT,
        NEW_CONNECT_STATE_PARKED,
    ):
        return rows.none()
    if str(state) == NEW_CONNECT_STATE_IN_PROGRESS_DRAFT:
        rows = rows.filter(waiting_on="")
    elif str(state) == NEW_CONNECT_STATE_PARKED:
        rows = rows.exclude(waiting_on="")

    term = (q or "").strip()
    if len(term) >= 2:
        # ⚠ **`reference` JOINED THE SEARCH ON 2026-09-21 WITH `BR-SHL-048 (d)`,
        # AND IT IS THE SAME LEG RATHER THAN A NEW ONE.** A draft finishing an
        # existing build now PRINTS that build's number, and a number a clerk
        # can read and cannot search reads as a broken search rather than as a
        # narrower one. It is still not a join: `reference` is a copied string
        # on the draft's own row, which is why clause (a) is untouched — see
        # `PARKED_NEW_CONNECT_SEARCH_LEGS_ARE_NARROWER`, whose remaining three
        # legs (premise, request and the connections table itself) genuinely
        # cannot reach a draft and still say so.
        rows = rows.filter(Q(subject_label__icontains=term) | Q(reference__icontains=term))
    return rows


def park_state(park: Any) -> str:
    """`in_progress_draft` or `parked` - told apart by ONE column.

    `WizardPark.waiting_on`'s own docstring: *"EMPTY MEANS *A DRAFT*, NOT *A
    PARK WITH NO REASON*"*. Every flow reads the same column the same way, and
    **the draft got no flag of its own on purpose**: two columns that must agree
    are two columns free to disagree.
    """
    return (
        NEW_CONNECT_STATE_PARKED
        if (park.waiting_on or "").strip()
        else NEW_CONNECT_STATE_IN_PROGRESS_DRAFT
    )


def park_row(park: Any, *, today: Any, zone: Any) -> dict[str, Any]:
    """One UNFINISHED new connect, in the SAME eight cells as a build row.

    ⚠ **THE SHAPE IS IDENTICAL AND THE CONTENT IS NOT, WHICH IS WHAT `row_kind`
    IS FOR.** Every key a build row carries is carried here, with a NAMED
    absence wherever a draft genuinely cannot answer. A row that simply omitted
    `orders` would render as an empty cell, and an empty cell and an absent fact
    are indistinguishable once drawn (`DEF-127`).

    ⚠ **THIS IS THE FLOW WITH THE LEAST TO SHOW, AND THAT IS HONEST RATHER THAN
    THIN.** The other four draft rows resolve an account or a unit through a
    copied id; a new connect has neither, by construction. What it has is the
    address the clerk typed, the step they reached, and why they stopped - and
    those three are exactly what the panel printed, so nothing a clerk could
    read before this ruling is lost by removing it.

    ⚠ **`orders` IS `0 of 0` AND NOT AN ABSENCE**, deliberately: no work order
    exists for a build that has not been raised, and *"none yet"* is a true
    answer where an absence would read as *"we cannot tell you"*. The fraction
    is B18 section 5.4.2's own rendering - *"not a percentage, not a bar alone"*.
    """
    parked_at = park.parked_at
    # `CR-150-BRC09` — the draft's own age, on the SAME clock and through
    # the SAME function a build row uses (`DEF-CUS-7620`). A page that
    # counted a draft's days one way and a build's another would be two
    # arithmetics under one column heading.
    age_days = _age_days(parked_at, today=today, zone=zone)
