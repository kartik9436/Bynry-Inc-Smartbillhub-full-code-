def _kpis(tenant_id: UUID, *, today: Any, zone: Any) -> dict[str, Any]:
    """The tiles of B18 §5.4.1 and of the 2026-09-28 drawing — see §2 for the
    arithmetic behind each figure and for the two things the seed cannot
    settle.

    Counts the CACHED `state` column, which is what the cache is for (§1).

    ⚠ **`waiting_on_anyone` JOINED THE STRIP ON 2026-09-28 AND
    `waiting_on_inspection` DID NOT LEAVE.** `00-list.png` captions the second
    tile *"Waiting on someone"*, which is every open build with ANY value in
    `waiting_on`; B18 §5.4.1 draws *"WAITING ON INSPECTION"*, which is the one
    literal. They are different questions and both are served, because the
    older tile is live on the screen today and removing a served figure to
    swap a caption would take a working tile off the page before its
    replacement is wired (hard-won law 2, the built-then-unwired direction).
    **The new tile is also the one that can FILTER** — §2's last warning says
    `waiting_on` is free text, so *"site inspection"* is invisible to the
    literal tile and counted by this one.

    ⛔ **`owed_on_open_builds` IS NULL WITH ITS REASON BESIDE IT** — see
    `OWED_ON_OPEN_BUILDS_UNAVAILABLE`. Exactly one of the two is ever set.
    """
    base = _connections(tenant_id)
    open_qs = base.filter(state__in=OPEN_STATES)

    per_build_units = (
        work_tables.ConnectionService.objects.filter(
            tenant_id=tenant_id, connection__in=open_qs.values("id"), unit__isnull=False
        )
        .values("connection_id")
        .annotate(units=Count("unit_id", distinct=True))
    )

    # Summed PER BUILD, not distinct across the tenant: two builds touching the
    # same unit are two units of work, and `42 across the 7 open builds` is the
    # UNITS column added up.
    units_awaiting = sum(row["units"] for row in per_build_units)

    oldest_row = (
        open_qs.annotate(started=Coalesce("submitted_at", "created_at"))
        .order_by("started", "id")
        .values("connection_no", "started", "waiting_on")
        .first()
    )
    oldest = None
    if oldest_row is not None:
        oldest = {
            # ⚠ **THE ROW'S OWN FUNCTION — `DEF-CUS-7620`.** This read
            # `(timezone.now() - started).days` until 2026-09-28: elapsed
            # 24-hour periods from UTC now, against the AGING column's
            # calendar-day subtraction in the utility's zone. Two arithmetics
            # under one word, agreeing on every seeded row because the fixture
            # backdates by whole days and disagreeing in production.
            "days": _age_days(oldest_row["started"], today=today, zone=zone),
            "connection_no": oldest_row["connection_no"],
            "waiting_on": oldest_row["waiting_on"],
        }

    return {
        "open": open_qs.count(),
        "waiting_on_inspection": open_qs.filter(
            waiting_on__iexact=WAITING_ON_INSPECTION
        ).count(),
        # The drawn `Waiting on someone` tile — ANY value, not one literal.
        # ⚠ **TRIMMED AND COMPARED IN SQL, NOT PULLED AND COUNTED IN PYTHON.**
        # `waiting_on` is a free-text column that can hold `"  "`, and
        # `park_state` already reads *empty after stripping* as *not waiting*;
        # a tile that counted a build waiting on two spaces would be a figure
        # no row on the page explains. `NFR-3`: it is a `WHERE`, over a tenant
        # that may hold 40,000 builds.
        # ⚠ **`output_field` IS NOT OPTIONAL HERE** — `waiting_on` is a
        # `TextField` and a bare `Value("")` resolves to `CharField`, so Django
        # refuses the mixed expression outright (`FieldError: Expression
        # contains mixed types`). The same reason the `UNION` arms below carry
        # typed `Value`s, one paragraph apart, found the same way: by running
        # it. It fails loudly rather than silently, which is the good case.
        "waiting_on_anyone": (
            open_qs.annotate(
                _waiting=Trim(Coalesce("waiting_on", Value(""), output_field=TextField()))
            )
            .exclude(_waiting="")
            .count()
        ),
        "partly_activated": base.filter(state=work_tables.PARTLY_ACTIVATED).count(),
        "units_awaiting_activation": units_awaiting,
        "oldest": oldest,
        # ⛔ `DEF-CUS-7619` — null, with its reason, and never a zero.
        "owed_on_open_builds": None,
        "owed_on_open_builds_unavailable": dict(OWED_ON_OPEN_BUILDS_UNAVAILABLE),
    }


