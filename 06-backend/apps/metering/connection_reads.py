def _unit_rows(tenant_id: UUID, service_rows: list[Any]) -> list[dict[str, Any]]:
    """`NCT-02.units` — `UNIT · TYPE · SERVICES · METERS · PLAN · OCCUPANCY ·
    ACCOUNT`, over the units THIS BUILD services.

    ⚠ **A NEW CONNECT ENDS WITH UNITS VACANT, SERVICE OFF AND NO ACCOUNT.**
    That is the terminal state and not an incomplete one, so `plan`,
    `occupancy` and `account_no` are each null-or-empty on purpose and the
    screen says which kind of nothing each is.

    `services` is what the BUILD maps to that unit — its `connection_services`
    rows — not every service point standing on it: a second connection at an
    existing block must not report the block's services as its own.

    `meters`, the account and the plan are three neighbours' facts and each is
    read through that neighbour's own published selector, never its tables
    (B1). `plan_ref` is memoised per plan id because a build's units are
    usually on ONE plan and asking 26 times is 26 queries for one answer.

    ⚠ **`occupancy` IS `None`, NEVER `"vacant"`, WHEN CUSTOMERS PUBLISHES NO
    ANSWER.** That is `seams.unit_is_occupied`'s own argument: BR-MET-036
    DERIVES occupancy from the active account, so with nobody to ask, *vacant*
    would be this module's guess rather than the rule's answer.
    """
    ordered_ids: list[str] = []
    services_by_unit: dict[str, list[str]] = {}
    for row in service_rows:
        if row.unit_id is None:
            continue
        unit_id = str(row.unit_id)
        if unit_id not in services_by_unit:
            services_by_unit[unit_id] = []
            ordered_ids.append(unit_id)
        services_by_unit[unit_id].append(row.service.code)
    if not ordered_ids:
        return []

    units = list(
        metering_models.Unit.objects.filter(tenant_id=tenant_id, id__in=ordered_ids).order_by(
            "label", "id"
        )
    )
    unit_ids = [str(unit.id) for unit in units]
    meters = seams.asset_counts_for_units(unit_ids)
    accounts = seams.accounts_for_units(unit_ids)
    customers_answers = seams.resolve("customers", "accounts_for_units", kind="selectors")

    plans: dict[str, str | None] = {}

    def plan_name(plan_id: Any) -> str | None:
        if plan_id is None:
            return None
        key = str(plan_id)
        if key not in plans:
            reference = seams.plan_ref(key)
            plans[key] = (reference or {}).get("name")
        return plans[key]

    # CR-070 wave B — `characteristic()` rides here, one query for the build.
    characteristics = _characteristics_by_unit(tenant_id, unit_ids)

    rows = []
    for unit in units:
        key = str(unit.id)
        account = accounts.get(key)
        rows.append(
            {
                "id": key,
                "label": unit.label,
                "unit_type": unit.unit_type,
                "services": sorted(set(services_by_unit.get(key, []))),
                "meters": meters.get(key, 0),
                "plan": plan_name(unit.rate_plan_id),
                "occupancy": (
                    ("occupied" if account is not None else "vacant")
                    if customers_answers is not None
                    else None
                ),
                "account_no": (account or {}).get("account_no"),
                # An EMPTY LIST is "nothing recorded", never zero — see
                # `_characteristics_by_unit`. The screen shows the absence.
                "characteristics": characteristics.get(key, []),
            }
        )
    return rows


def _characteristics_by_unit(
    tenant_id: UUID, unit_ids: list[str]
) -> dict[str, list[dict[str, Any]]]:
    """`characteristic()` RIDING INSIDE THE DETAIL — CR-070 wave B, `US-WRK-002`.

    The blueprint's §7 counts sixteen things this module can do that only a
    Python shell can reach: fourteen writers and TWO READERS. `outstanding_work`
    is the one already served below; this is the other. Neither gets a route:
    a per-key GET would be a second door onto a fact the screen is already
    holding, and `07-endpoints.md` §1 says so in one line — *"The two readers
    ride inside `GET /connections/{id}`."*

    ⚠ **ONE QUERY FOR THE WHOLE BUILD, NOT ONE PER UNIT PER SERVICE.**
    `connections.characteristic()` answers ONE `(unit, service, key)` and is the
    right shape for the pricing path that calls it; asking it here would be 26
    units × 4 services × n keys round trips for one screen. This reads the same
    table under the same tenant filter and hands the rows back grouped, which is
    what a screen needs and what `_unit_rows`' own cost note demands.

    ⚠ **THE UNIT IS A COLUMN AND IS NEVER FOLDED INTO THE VALUE** — hard rule 3,
    and the reason `BR-MET-108` refused a column per service. `value` and
    `unit_of_measure` cross the wire apart, and the screen joins them for
    display or not at all.

    An empty list means NO CHARACTERISTIC RECORDED. It does not mean the unit
    does not take the service and it never means zero — `characteristic()`'s own
    docstring, kept here because a caller that reads absence as zero is the
    defect that docstring was written against.
    """
    if not unit_ids:
        return {}
    rows = (
        work_tables.ServiceCharacteristic.objects.filter(tenant_id=tenant_id, unit_id__in=unit_ids)
        .select_related("service")
        .order_by("unit_id", "service__code", "key")
    )
    grouped: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        grouped.setdefault(str(row.unit_id), []).append(
            {
                "service": row.service.code,
                "key": row.key,
                "value": row.value,
                "unit_of_measure": row.unit_of_measure,
            }
        )
    return grouped


def _asset_rows(unit_rows: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], int | None]:
    """`NCT-02.assets`, and the sub-meter count beside its red-ruled note.

    Four of the nine drawn columns are served and five are null with one stated
    reason — see §5.2, which also records why `parent` is null on a sub-meter.

    `sub_meter_links` counts the assets whose qualifier is `sub`. It is `None`
    when the assets selector is not published at all, because an empty list
    cannot tell *"no sub-meters"* from *"nobody answered"* — and a zero there
    would read as *"we checked and there are none"*.
    """
    published = seams.resolve("assets", "assets_on_unit", kind="selectors") is not None
    rows: list[dict[str, Any]] = []
    sub_meter_links = 0
    for unit in unit_rows:
        for asset in seams.assets_on_unit(unit["id"]):
            if asset.get("qualifier") == "sub":
                sub_meter_links += 1
            rows.append(
                {
                    "id": asset.get("id"),
                    "asset_no": asset.get("asset_no"),
                    "service": None,
                    "kind": asset.get("type"),
                    "unit_label": unit["label"],
                    "size": None,
                    "multiplier": None,
                    "read_method": None,
                    "parent": None,
                    "status": None,
                }
            )
    return rows, (sub_meter_links if published else None)


def _history(tenant_id: UUID, connection_id: Any) -> list[dict[str, Any]]:
    """`NCT-02.history` — `WHEN · WHO · WHAT HAPPENED`, newest first.

    Audit's own two published functions do the reading: `entity_trail` is the
    per-entity window every Audit tab in this product uses, and `audit_row` is
    its payload builder — so no audit column is touched from here. See §5.3 for
    what is NOT in this trail and why it is reported rather than looped over.
    """
    trail = seams.resolve("audit", "entity_trail", kind="selectors")
    build_row = seams.resolve("audit", "audit_row", kind="selectors")
    if trail is None or build_row is None:
        return []
    payloads = [build_row(row, {}) for row in trail(tenant_id, "connection", connection_id)]
    lookup = seams.resolve("audit", "actor_names", kind="selectors")
    actor_ids = [payload["actor"]["id"] for payload in payloads if payload.get("actor") is not None]
    names = lookup(tenant_id, actor_ids) if lookup is not None and actor_ids else {}
    history = []
    for payload in payloads:
        actor = payload.get("actor")
        history.append(
            {
                "at": payload["created_at"],
                "who": (names.get(actor["id"]) or actor["id"]) if actor else SYSTEM_ACTOR,
                "what": payload["action"],
            }
        )
    return history


def connection_detail(connection_id: Any) -> dict[str, Any]:
    """`GET /connections/{id}` — everything `NCT-02`'s six tabs draw.

    The shape is `07-frontend/src/features/customers/newConnectEndpoints.ts`'s
    `ConnectionDetail`, field for field. Every figure on it comes from a named
    function in `connections.py` or from a neighbour's published selector;
    **nothing here computes a business answer of its own**, and the four fields
    the product cannot produce come back null beside `unavailable`'s reasons
    rather than as a zero, a dash or a guessed word.

    Query cost is bounded by the build rather than by the tenant: one row read,
    one pass over its `connection_services`, one over its `work_orders`, one
    grouped count per neighbour for the units, and one audit trail. The
    per-asset reads are the exception and are §5.2's reported seam gap.
    """
    tenant_id = _tenant_id()
    connection = _connection_or_404(tenant_id, connection_id)

    service_rows = list(
        work_tables.ConnectionService.objects.filter(
            tenant_id=tenant_id, connection_id=connection.id
        ).select_related("service")
    )
    orders = list(
        work_tables.WorkOrder.objects.filter(tenant_id=tenant_id, connection_id=connection.id)
        .select_related("service", "unit", "blocked_by", "accepted_by")
        .order_by("created_at", "id")
    )
    unit_rows = _unit_rows(tenant_id, service_rows)
    assets, sub_meter_links = _asset_rows(unit_rows)
    done, total = w6.order_progress(connection)
    premises = connection.premises
    request = connection.service_request
    started = connection.submitted_at or connection.created_at

    return {
        "id": str(connection.id),
        "connection_no": connection.connection_no,
        # THE DERIVATION, never the cached column — §1 and §5.1.
        "state": w6.connection_state(connection),
        # ⚠ **`None` ON A DRAFT RAISED FROM AN APPLICATION WHOSE ADDRESS HAD
        # NOT RESOLVED — `DEF-CUS-6109`.** The whole block rather than four
        # nulls inside it: *there is no address yet* is one fact, and a screen
        # reading `premise_no` off an object whose every field is null cannot
        # tell that from a property with no number.
        "premises": _premises_block(premises),
        # Null on purpose: the three parts of the drawn sub-line are served
        # below and the SENTENCE is the catalogue's — see §5's second warning.
        "unit_summary": None,
        "applicant": getattr(request, "applicant_name", None),
        "request_no": getattr(request, "request_no", None),
        # ⚠ **`DEF-CUS-6109` — WHAT THE APPLICATION ALREADY ANSWERED, SO THE
        # CLERK IS NOT ASKED IT TWICE.** `None` on a build raised directly.
        "prefill": _request_prefill(request),
        # What the ORDERS say — `"mixed"` when they disagree, which §8.3 calls
        # the normal case, and None when there are no orders to read.
        "mode": w6.connection_mode(connection),
        # Start = submitted, falling back to created: a build becomes the
        # utility's to deliver when it is requested, and a draft nobody
        # submitted has only the day somebody opened it (§2's `oldest` rule).
        "started_at": started.isoformat() if started is not None else None,
        "target_activation": (
            connection.target_activation.isoformat() if connection.target_activation else None
        ),
        "waiting_on": connection.waiting_on,
        "units": _unit_counts(tenant_id, [connection.id]).get(connection.id, 0),
        "orders": {"done": done, "total": total},
        "services": [_service_block(block) for block in w6.service_progress(connection)],
        "work_orders": [_work_order_row(order) for order in orders],
        "unit_rows": unit_rows,
        "assets": assets,
        "sub_meter_links": sub_meter_links,
        "quote_total": _pair(connection.quote_total),
        # DEF-678 · nothing records a settlement — see DETAIL_ABSENCES.
        "quote_settled_at": None,
        # OQ-379 · the quote is a figure, and its lines were never raised.
        "charges": None,
        # No consumer category exists for a vacant unit — DETAIL_ABSENCES.
        "deposit": None,
        # BR-MET-114 — human-authored, never derived, and never a blocker.
        "outstanding": w6.outstanding_work(connection.id),
        "history": _history(tenant_id, connection.id),
        "owner_account_no": (
            connection.owner_account.account_no if connection.owner_account_id else None
        ),
        "unavailable": [dict(absence) for absence in DETAIL_ABSENCES],
    }


