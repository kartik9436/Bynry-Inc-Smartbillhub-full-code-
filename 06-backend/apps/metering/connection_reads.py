def _tenant_clock() -> tuple[Any, Any]:
    """Today and the zone the utility is on, read ONCE for a whole page.

    ⚠ **BOTH HALVES, BECAUSE AN AGE IS A SUBTRACTION OF TWO DAYS.**
    `tenant_today()` gives the left one; the right one is a stored `datetime`
    and turning THAT into a day needs the same zone, or the two ends of one sum
    are read on two clocks — `DEF-094`'s shape, and `DEF-CUS-6433`'s measured
    cost one module over (five hours of every evening, every row a day old too
    soon). `service_request_reads.list_row` resolves the pair the same way and
    says so for the same reason.
    """
    return seams.tenant_today(), seams.tenant_timezone()


def _age_days(started: Any, *, today: Any, zone: Any) -> int | None:
    """How many of the UTILITY'S OWN DAYS a build has been running.

    ⚠ **ONE FUNCTION FOR THE ROW AND THE TILE — `DEF-CUS-7620`.** `_kpis`'
    `oldest` counted `(timezone.now() - started).days` until 2026-09-28: elapsed
    24-hour periods measured from UTC now, which is a different arithmetic from
    a calendar-day subtraction and disagrees with it around the zone offset.
    Nothing caught it because the fixture backdates by whole multiples of 24
    hours, so both answers are equal on every seeded row. A row and a tile that
    print the same word must not be able to print different numbers, so there
    is exactly one function and both call it.

    **START = `submitted_at`, FALLING BACK TO `created_at`** — §2's `oldest`
    rule, unchanged: a build becomes the utility's to deliver when it is
    requested, and a draft nobody submitted has only the day somebody opened it.

    `None` in, `None` out. A build with no date has no age, and that is not the
    claim *"it is new"*.
    """
    if started is None:
        return None
    began = started.astimezone(zone).date() if hasattr(started, "astimezone") else started
    return (today - began).days


def _started_at(connection: Any) -> Any:
    """§2's start, in one place so the row, the tile and the detail agree."""
    return connection.submitted_at or connection.created_at


#: The build's own stamped facts, NEWEST WINS and ties break in THIS ORDER.
#:
#: ⚠ **THESE ARE THE COLUMNS THE MODEL ALREADY CALLS EVENTS** — `Connection`'s
#: own docstring: *"The three facts NO service can express are stored as
#: timestamps"* — plus the two the lifecycle adds. `updated_at` is deliberately
#: absent: `auto_now` moves on any write, including a cache refresh, so it
#: records that a row changed and never what happened to the build.
STAMPED_EVENTS: tuple[tuple[str, str], ...] = (
    ("cancelled", "cancelled_at"),
    ("activated", "activated_at"),
    ("held", "held_at"),
    ("submitted", "submitted_at"),
    ("created", "created_at"),
)


def _last_stamped_event(connection: Any) -> dict[str, Any] | None:
    """`Last event` behind the column chooser — the build's own newest stamp.

    ⚠ **IT IS THE BUILD'S STAMPS AND IT IS NOT THE AUDIT TRAIL, AND THE NAME
    SAYS SO ON PURPOSE.** The detail's History tab reads
    `audit.selectors.entity_trail`, which addresses ONE entity — §5.3 already
    REPORTS that folding several in needs an audit read taking many ids, and
    audit publishes none. A list column calling `entity_trail` per row would be
    a query per row to draw one optional cell. So this answers from columns the
    row already carries, at zero extra cost, and is called `last_stamped_event`
    rather than `last_event` so no later lane reads it as the trail's newest
    line (`amendment_history_is_not_a_permanent_record`'s lesson: rename the
    key rather than reword the sentence).

    `what` is a TOKEN and never a sentence — `_history`'s posture, for
    `_history`'s reason: a token can be translated and an English sentence
    composed on the server cannot.

    Every build has a `created_at`, so `None` here means a row with no stamps
    at all, which the store does not produce.
    """
    best: tuple[Any, str] | None = None
    for token, field in STAMPED_EVENTS:
        at = getattr(connection, field, None)
        if at is None:
            continue
        if best is None or at > best[0]:
            best = (at, token)
    if best is None:
        return None
    return {"at": best[0].isoformat(), "what": best[1]}


