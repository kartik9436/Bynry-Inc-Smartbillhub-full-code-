"""Render the examples section of `04-docs/03-contracts/technician-api.md`
from one or more capture files, and splice it between the doc's markers.

    python3 10-scripts/technician_api_walk.py … --capture /tmp/c1.json
    python3 10-scripts/technician_api_contract_examples.py /tmp/c1.json [/tmp/c2.json …]

One example per (method, route, status). Long lists are cut to their first
three entries and tokens to 24 characters, and the cut is SAID in the block,
so a reader never mistakes a shortened example for the whole answer.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

DOC = Path(__file__).resolve().parents[1] / "04-docs/03-contracts/technician-api.md"
START = "<!-- examples:start (generated by 10-scripts/technician_api_contract_examples.py) -->"
END = "<!-- examples:end -->"
UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")


def shorten(value, depth=0):
    if isinstance(value, dict):
        return {k: shorten(v, depth + 1) for k, v in value.items()}
    if isinstance(value, list):
        head = [shorten(v, depth + 1) for v in value[:3]]
        if len(value) > 3:
            head.append(f"… {len(value) - 3} more (cut for the doc)")
        return head
    # A token, a hash or any long unbroken string (a credential must never be
    # published whole, even a demo one).
    if isinstance(value, str) and len(value) > 60 and " " not in value:
        return value[:24] + "…(cut)"
    return value


def main(paths: list[str]) -> int:
    log = []
    for p in paths:
        log += json.loads(Path(p).read_text())
    seen: dict[tuple, dict] = {}
    for entry in log:
        route = UUID.sub("{id}", entry["path"].split("?")[0])
        key = (route, entry["method"], entry["status"])
        seen.setdefault(key, entry)
    out = [START, ""]
    for (route, method, status), e in sorted(seen.items()):
        query = e["path"].split("?", 1)[1] if "?" in e["path"] else ""
        out.append(f"#### `{method} {route}{'?' + query if query else ''}` → **{status}** ({e['who']})")
        out.append("")
        if e.get("request") not in (None, {}, ""):
            out.append("Request:")
            out.append("```json")
            out.append(json.dumps(shorten(e["request"]), indent=1, ensure_ascii=False, default=str))
            out.append("```")
        out.append("Response:")
        out.append("```json")
        out.append(json.dumps(shorten(e["response"]), indent=1, ensure_ascii=False, default=str))
        out.append("```")
        out.append("")
    out.append(END)
    text = DOC.read_text()
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        new = head + "\n".join(out) + tail
    else:
        new = text.rstrip() + "\n\n" + "\n".join(out) + "\n"
    assert len(new) > len(text) // 2, "refusing to write a doc that shrank by half"
    DOC.write_text(new)
    print(f"{len(seen)} examples written into {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
